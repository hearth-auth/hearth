#!/usr/bin/env bash
# Authentik for the same-hardware comparison (#913): one server with
# Authentik's server and worker and their PostgreSQL (compose.yaml), the
# stress realm (realm.py), and the seed.
#
# Usage: authentik.sh <command>
#   up            make the bundle (first time), start PostgreSQL and the worker
#                 with 1 thread until it has applied Authentik's blueprints and
#                 tls.yaml, then the worker with its 2 threads and the server,
#                 wait until Authentik answers on its HTTPS listener with the
#                 run's TLS leaf (tls.yaml), create the providers,
#                 the applications, the service account and the login users
#                 (first time, realm.py), then wait until the worker has no
#                 task left (settle)
#   bundle        make the bundle (first time) and nothing else
#   seed <from> <to>
#                 create users without a password bulk<from> .. bulk<to - 1>:
#                 realm.py writes them as blueprints (SEED_BATCH users per
#                 file) and SEED_PROCS one-off worker containers apply them
#                 (`ak apply_blueprint`, Authentik's blueprint importer, each
#                 file in one transaction); prints the time until the last
#                 file is applied (the users are then usable) and the number
#                 of users created
#   settle        wait until the worker has no task queued or running
#   hashes        print the parameters of the stored password hashes (no hash)
#   tasks         print the worker's tasks by name and state, and the number of
#                 email tasks (none may come from a journey or the seed)
#   restart       restart the server and the worker (the data stays)
#   down          remove the containers and the volumes, and with them the realm
#                 (the images and the bundle's passwords stay)
#
# Environment:
#   BUNDLE              the bundle directory (default ../.build/authentik): CA,
#                       TLS leaf, server.env, generator.env; mode 0700
#   SERVER_IP           the address the generator dials (default 127.0.0.1)
#   AK_BIND             the address Authentik's listener binds to (default 127.0.0.1)
#   LOGIN_USERS         users with a password (default 1000, as in #647)
#   SEED_BATCH, SEED_PROCS     users per seed file (default 1000) and the
#                       number of one-off containers that apply them (default 2)
#   SERVER_MEM_LIMIT, WORKER_MEM_LIMIT
#                       the containers' memory limits (default 1280m, 768m)
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
compare=$(cd "$here/.." && pwd)
export BUNDLE=${BUNDLE:-$compare/.build/authentik}
export AK_HOST=authentik.stress.test
AK_PORT=9443
set -a
# shellcheck disable=SC1091
. "$compare/images.env"
set +a

log() { printf 'authentik: %s\n' "$*" >&2; }
die() {
  log "FAILED: $*"
  exit 2
}
compose() { docker compose -f "$here/compose.yaml" --env-file "$BUNDLE/server.env" "$@"; }
# Letters and digits only.
password() { openssl rand -base64 48 | tr -d '/+=' | cut -c1-24; }

make_bundle() {
  # A whole bundle (an earlier up's, or a ramp server's copy of the seed's,
  # whose passwords the store knows) is kept; a new or an empty directory
  # (remote.sh data-new makes /data/bundle) gets one.
  [ ! -f "$BUNDLE/server.env" ] || [ ! -f "$BUNDLE/generator.env" ] || return 0
  log "making the bundle in $BUNDLE"
  mkdir -p "$BUNDLE"
  chmod 0700 "$BUNDLE"
  bash "$compare/tls.sh" "$BUNDLE" "$AK_HOST"
  # The worker runs as its image's user and must read the leaf (tls.yaml); the
  # bundle directory (0700) keeps other users of this host out.
  chmod 0755 "$BUNDLE/tls"
  chmod 0644 "$BUNDLE/tls/https.key" "$BUNDLE/tls/https.crt"
  # The blueprints the one-off containers apply (realm.py); those containers
  # run as this host's user, so the files stay owner-only.
  mkdir -m 0700 "$BUNDLE/blueprints"
  local admin_password admin_hash
  admin_password=$(password)
  # The akadmin user's password reaches Authentik only as a hash in
  # Authentik's default format (automated install: the _HASH variable rather
  # than the plaintext one); realm.py reads the password on stdin.
  admin_hash=$(printf '%s' "$admin_password" | python3 -I "$here/realm.py" hash)
  (
    umask 077
    # Compose variables (compose.yaml hands each container its own keys). The
    # hash is single-quoted: docker compose would expand its `$` otherwise.
    {
      printf 'DB_PASSWORD=%s\nAUTHENTIK_SECRET_KEY=%s\nBOOTSTRAP_TOKEN=%s\n' \
        "$(password)" "$(openssl rand -base64 60 | tr -d '\n/+=')" "$(openssl rand -hex 32)"
      printf "ADMIN_EMAIL=admin@%s\nADMIN_PASSWORD_HASH='%s'\n" "$AK_HOST" "$admin_hash"
    } > "$BUNDLE/server.env"
    # The client ids and secrets are generated by Authentik; realm.py adds
    # them (STRESS_APP_CLIENT_ID, STRESS_API_*, STRESS_CC_*).
    cat > "$BUNDLE/generator.env" << EOF
PRODUCT=authentik
STRESS_BASE=https://$AK_HOST:$AK_PORT
STRESS_HOST=$AK_HOST
STRESS_SERVER_IP=${SERVER_IP:-127.0.0.1}
STRESS_REDIRECT_URI=https://app.stress.test/callback
STRESS_LOGIN_USERS=${LOGIN_USERS:-1000}
STRESS_USER_PASSWORD=$(password)
STRESS_ADMIN_EMAIL=admin@$AK_HOST
STRESS_ADMIN_PASSWORD=$admin_password
STRESS_REALM=stress
EOF
  )
}

# Ready: the server answers its readiness check over TLS with the run's leaf
# (curl checks it against the run's CA), so tls.yaml has been applied.
ready() {
  curl -fsS -o /dev/null --max-time 4 --cacert "$BUNDLE/ca.crt" \
    --resolve "$AK_HOST:$AK_PORT:${SERVER_IP:-127.0.0.1}" "https://$AK_HOST:$AK_PORT/-/health/ready/" 2> /dev/null
}

wait_ready() {
  local i
  for i in $(seq 1 300); do
    if ready; then
      log "Authentik is ready after ${i} s"
      return 0
    fi
    sleep 1
  done
  compose logs --tail 20 server worker >&2
  die "Authentik is not ready after 300 s"
}

sql() { compose exec -T postgres psql -U authentik -d authentik -At -c "$1"; }

# Applies blueprints (paths under <bundle>/blueprints) in a one-off worker
# container: Authentik's blueprint importer (validate, then apply in one
# transaction) outside the worker's task queue and outside an HTTP request, so
# the import itself queues no task and writes no audit event. The running
# worker never sees the files (they are mounted only here), so its blueprint
# discovery does not parse them every hour. The container runs as this host's
# user, who owns the (0600) files.
apply_blueprints() {
  local files=() f
  for f in "$@"; do files+=("compare-seed/$f"); done
  compose run --rm --no-deps -T --user "$(id -u):$(id -g)" \
    -v "$BUNDLE/blueprints:/blueprints/compare-seed:ro" worker apply_blueprint "${files[@]}" > /dev/null 2>&1
}

# The worker's tasks that are due and not finished.
pending_tasks() {
  sql "SELECT count(*) FROM authentik_tasks_task
         WHERE state IN ('queued', 'consumed', 'preprocess', 'running', 'postprocess')
           AND coalesce(eta, now()) <= now()"
}

cmd_settle() {
  local start n
  start=$(date +%s)
  while n=$(pending_tasks) && [ "$n" -gt 0 ]; do
    sleep 5
  done
  log "the worker has no task left after $(($(date +%s) - start)) s"
}

# Where the worker is with the blueprints, given the time (UTC) it was started:
# busy (it has not finished a discovery since, or a blueprint task is queued
# or running), failed (none is left, but a blueprint is not applied) or done.
# Authentik's migrations make the instances (status unknown) before the
# worker's first discovery queues their tasks.
blueprint_state() {
  sql "SELECT CASE
         WHEN NOT EXISTS (SELECT 1 FROM authentik_tasks_task
                           WHERE actor_name = 'authentik.blueprints.v1.tasks.blueprints_discovery'
                             AND state = 'done' AND mtime >= '$1'::timestamptz) THEN 'busy'
         WHEN EXISTS (SELECT 1 FROM authentik_tasks_task
                       WHERE actor_name LIKE 'authentik.blueprints.%'
                         AND state NOT IN ('done', 'rejected')) THEN 'busy'
         WHEN NOT EXISTS (SELECT 1 FROM authentik_blueprints_blueprintinstance
                           WHERE path = 'compare/tls.yaml') THEN 'failed'
         WHEN EXISTS (SELECT 1 FROM authentik_blueprints_blueprintinstance
                       WHERE enabled AND status <> 'successful') THEN 'failed'
         ELSE 'done' END"
}

# The blueprints not applied, with their status.
blueprints_not_applied() {
  sql "SELECT path || ' (' || status || ')' FROM authentik_blueprints_blueprintinstance
         WHERE enabled AND status <> 'successful' ORDER BY path" | paste -sd ' '
}

cmd_up() {
  make_bundle
  # At its first start the worker applies the vendor's blueprints (flows,
  # scope mappings; realm.py needs them all) and tls.yaml, each in one
  # transaction, and the server's start and the worker's both queue a
  # discovery, so each blueprint is applied twice. With the worker's 2 threads
  # two of them can overlap and deadlock in PostgreSQL (#913: flow-oobe.yaml
  # and flow-default-authentication-flow.yaml update the same two stages in
  # the opposite order), leaving one in `error`, in about 1 of 2 fresh starts.
  # So the worker starts alone with 1 thread, which applies them one at a
  # time, and gets its 2 threads (Authentik's default, compose.yaml) back
  # before the server starts: a run has the same worker as before. A ramp's
  # store has them all applied already, and the worker finds nothing to apply.
  local since i state=busy
  since=$(date -u +%Y-%m-%dT%H:%M:%S.%NZ)
  AK_WORKER_THREADS=1 compose up -d worker
  for i in $(seq 1 600); do
    state=$(blueprint_state "$since" 2> /dev/null) || state=busy
    [ "$state" = busy ] || break
    sleep 1
  done
  case $state in
    done) log "the worker has applied every blueprint after ${i} s" ;;
    failed) die "the worker has not applied every blueprint: $(blueprints_not_applied)" ;;
    *) die "the worker has not applied every blueprint after 600 s: $(blueprints_not_applied 2> /dev/null)" ;;
  esac
  # The worker again with 2 threads, and the server: it reads the brand's
  # certificate (tls.yaml, applied) at its start and serves the run's leaf.
  compose up -d
  wait_ready
  if [ ! -e "$BUNDLE/realm.done" ]; then
    log "creating the providers, the applications, the service account and the login users"
    python3 -I "$here/realm.py" "$BUNDLE"
    apply_blueprints logins.yaml
    local n
    n=$(sql "SELECT count(*) FROM authentik_core_user WHERE username LIKE 'user______@%'")
    [ "$n" = "$(sed -n 's/^STRESS_LOGIN_USERS=//p' "$BUNDLE/generator.env")" ] || die "$n login users, not all"
    touch "$BUNDLE/realm.done"
  fi
  # Setting a login user's password hash writes an audit event, which queues
  # notification tasks: let the worker finish them before a run.
  cmd_settle
}

cmd_seed() {
  local from=${1:?usage: authentik.sh seed <from> <to>} to=${2:?usage: authentik.sh seed <from> <to>}
  local dir=seed-$from-$to procs=${SEED_PROCS:-2} start p files n
  log "seeding users $from .. $((to - 1))"
  start=$(date +%s)
  python3 -I "$here/realm.py" bulk "$BUNDLE/blueprints/$dir" "$AK_HOST" "$from" "$to" "${SEED_BATCH:-1000}"
  mapfile -t files < <(cd "$BUNDLE/blueprints" && ls "$dir"/*.yaml)
  log "${#files[@]} files written after $(($(date +%s) - start)) s"
  # File i goes to container i % procs.
  for p in $(seq 0 $((procs - 1))); do
    local mine=() i
    for i in "${!files[@]}"; do
      [ $((i % procs)) -ne "$p" ] || mine+=("${files[$i]}")
    done
    [ "${#mine[@]}" -eq 0 ] || apply_blueprints "${mine[@]}" &
  done
  wait
  n=$(sql "SELECT count(*) FROM authentik_core_user WHERE username LIKE 'bulk%' AND username >= '$(printf 'bulk%08d' "$from")' AND username < '$(printf 'bulk%08d' "$to")'")
  log "seed: $n of $((to - from)) users created, all applied after $(($(date +%s) - start)) s"
  rm -rf "${BUNDLE:?}/blueprints/$dir"
}

# The parameters of the stored password hashes (Django's format: algorithm and
# iterations, the part before the salt), counted. No hash is printed.
cmd_hashes() {
  sql "SELECT CASE WHEN password LIKE '!%' THEN 'unusable (no password)'
                   ELSE split_part(password, '\$', 1) || '\$' || split_part(password, '\$', 2) END, count(*)
         FROM authentik_core_user GROUP BY 1 ORDER BY 2 DESC"
}

# The worker's tasks (Dramatiq messages in PostgreSQL), by actor and state, and
# the email tasks among them.
cmd_tasks() {
  sql "SELECT actor_name, state, count(*) FROM authentik_tasks_task GROUP BY 1, 2 ORDER BY 3 DESC"
  printf 'email tasks: %s\n' "$(sql "SELECT count(*) FROM authentik_tasks_task WHERE actor_name LIKE '%email%'")"
}

cmd_restart() {
  compose restart server worker
  wait_ready
  cmd_settle
}

cmd_down() {
  compose down --volumes --remove-orphans
  # The realm went with the database: the next `up` makes it again.
  rm -f "$BUNDLE/realm.done"
}

case ${1:-} in
  bundle) make_bundle ;;
  up) cmd_up ;;
  seed) shift && cmd_seed "$@" ;;
  settle) cmd_settle ;;
  hashes) cmd_hashes ;;
  tasks) cmd_tasks ;;
  restart) cmd_restart ;;
  down) cmd_down ;;
  *) sed -n '2,/^set -euo/p' "$0" | sed '$d' >&2 && exit 2 ;;
esac
