#!/usr/bin/env bash
# Ory (Hydra + Kratos) for the same-hardware comparison (#913): one server with
# Hydra, Kratos, Ory's reference login and consent UI and their PostgreSQL
# (compose.yaml), the stress realm (realm.py), and the seed.
#
# Usage: ory.sh <command>
#   up            make the bundle (first time), start PostgreSQL, the
#                 migrations, Hydra, Kratos and the UI, wait until all three
#                 answer, create the clients and the login users (first time,
#                 realm.py)
#   bundle        make the bundle (first time) and nothing else
#   seed <from> <to>
#                 import users without a usable password (realm.py
#                 unusable_hash) bulk<from> .. bulk<to - 1> through Kratos's
#                 PATCH /admin/identities (k6/prepare.js, PRODUCT=ory); prints
#                 the import time (duration_s) from <bundle>/out/seed-<from>-<to>.json,
#                 then the time until Kratos's admin API lists the last one (the
#                 seed time)
#   hashes        print the parameters of the stored password hashes (no hash)
#   messages      print the number of messages Kratos has queued (courier)
#   restart       restart Hydra, Kratos and the UI (the data stays)
#   down          remove the containers and the database volume, and with them the
#                 realm (the images and the bundle's passwords stay)
#
# Environment:
#   BUNDLE              the bundle directory (default ../.build/ory): CA, TLS
#                       leaf, server.env, generator.env; mode 0700
#   SERVER_IP           the address the generator dials (default 127.0.0.1)
#   ORY_BIND            the address the Ory listeners bind to (default 127.0.0.1)
#   LOGIN_USERS         users with a password (default 1000, as in #647)
#   IMPORT_BATCH, IMPORT_VUS   seed batch size (at most 1000, Kratos's limit)
#                       and concurrency (prepare.js)
#   HYDRA_MEM_LIMIT, KRATOS_MEM_LIMIT, UI_MEM_LIMIT
#                       the containers' memory limits (default 512m, 1g, 512m)
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
compare=$(cd "$here/.." && pwd)
export BUNDLE=${BUNDLE:-$compare/.build/ory}
export ORY_HOST=ory.stress.test
set -a
# shellcheck disable=SC1091
. "$compare/images.env"
set +a

log() { printf 'ory: %s\n' "$*" >&2; }
die() {
  log "FAILED: $*"
  exit 2
}
compose() { docker compose -f "$here/compose.yaml" --env-file "$BUNDLE/server.env" "$@"; }
# Letters and digits only (initdb.sh puts the database passwords in SQL).
password() { openssl rand -base64 48 | tr -d '/+=' | cut -c1-24; }
# Kratos's cipher secret must be exactly 32 characters.
secret32() { openssl rand -base64 48 | tr -d '/+=' | cut -c1-32; }

make_bundle() {
  # A whole bundle (an earlier up's, or a ramp server's copy of the seed's,
  # whose passwords the store knows) is kept; a new or an empty directory
  # (remote.sh data-new makes /data/bundle) gets one.
  [ ! -f "$BUNDLE/server.env" ] || [ ! -f "$BUNDLE/generator.env" ] || return 0
  log "making the bundle in $BUNDLE"
  mkdir -p "$BUNDLE"
  chmod 0700 "$BUNDLE"
  bash "$compare/tls.sh" "$BUNDLE" "$ORY_HOST"
  # Hydra, Kratos and the UI run as their images' users and must read the
  # leaf and the CA; the bundle directory (0700) keeps other users of this
  # host out.
  chmod 0755 "$BUNDLE/tls"
  chmod 0644 "$BUNDLE/tls/https.key" "$BUNDLE/tls/https.crt" "$BUNDLE/ca.crt"
  local admin_password
  admin_password=$(password)
  (
    umask 077
    # Compose variables (compose.yaml hands each container its own keys).
    {
      printf 'DB_ADMIN_PASSWORD=%s\nHYDRA_DB_PASSWORD=%s\nKRATOS_DB_PASSWORD=%s\n' \
        "$(password)" "$(password)" "$(password)"
      printf 'HYDRA_SECRET_SYSTEM=%s\nHYDRA_SECRET_COOKIE=%s\nHYDRA_SECRET_PAGINATION=%s\n' \
        "$(secret32)" "$(secret32)" "$(secret32)"
      printf 'KRATOS_SECRET_DEFAULT=%s\nKRATOS_SECRET_COOKIE=%s\nKRATOS_SECRET_CIPHER=%s\nKRATOS_SECRET_PAGINATION=%s\n' \
        "$(secret32)" "$(secret32)" "$(secret32)" "$(secret32)"
      printf 'UI_COOKIE_SECRET=%s\nUI_CSRF_COOKIE_SECRET=%s\n' "$(secret32)" "$(secret32)"
    } > "$BUNDLE/server.env"
    # The client ids and secrets are generated by Hydra; realm.py adds them
    # (STRESS_APP_CLIENT_ID, STRESS_API_*), and the bulk users' hash.
    cat > "$BUNDLE/generator.env" << EOF
PRODUCT=ory
STRESS_BASE=https://$ORY_HOST:4444
STRESS_HOST=$ORY_HOST
STRESS_SERVER_IP=${SERVER_IP:-127.0.0.1}
STRESS_REDIRECT_URI=https://app.stress.test/callback
STRESS_LOGIN_USERS=${LOGIN_USERS:-1000}
STRESS_USER_PASSWORD=$(password)
STRESS_ADMIN_EMAIL=admin@$ORY_HOST
STRESS_ADMIN_PASSWORD=$admin_password
STRESS_REALM=stress
EOF
  )
}

# The health endpoints of Hydra (admin port), Kratos (admin port) and the UI.
ready() {
  local port_path port
  for port_path in 4445/health/ready 4434/admin/health/ready 4455/health/ready; do
    port=${port_path%%/*}
    curl -fsS -o /dev/null --max-time 4 --cacert "$BUNDLE/ca.crt" \
      --resolve "$ORY_HOST:$port:${SERVER_IP:-127.0.0.1}" "https://$ORY_HOST:$port_path" 2> /dev/null || return 1
  done
}

wait_ready() {
  local i
  for i in $(seq 1 180); do
    if ready; then
      log "Hydra, Kratos and the UI are ready after ${i} s"
      return 0
    fi
    sleep 1
  done
  compose logs --tail 20 hydra kratos ui >&2
  die "Ory is not ready after 180 s"
}

cmd_up() {
  make_bundle
  compose up -d
  wait_ready
  if [ ! -e "$BUNDLE/realm.done" ]; then
    log "creating the clients and the login users"
    python3 -I "$here/realm.py" "$BUNDLE"
    touch "$BUNDLE/realm.done"
  fi
}

sql() { compose exec -T postgres psql -U postgres -d kratos -At -c "$1"; }

cmd_seed() {
  local from=${1:?usage: ory.sh seed <from> <to>} to=${2:?usage: ory.sh seed <from> <to>}
  local out=seed-$from-$to.json start
  log "seeding users $from .. $((to - 1))"
  start=$(date +%s)
  bash "$compare/k6.sh" "$BUNDLE" prepare.js IMPORT_FROM="$from" IMPORT_TO="$to" \
    IMPORT_BATCH="${IMPORT_BATCH:-1000}" IMPORT_VUS="${IMPORT_VUS:-4}" PREPARE_OUT="/out/$out" > /dev/null
  python3 -I - "$BUNDLE/out/$out" << 'PY'
import json, sys
r = json.load(open(sys.argv[1]))
print(f"seed: {r['users_imported']} imported, {r['users_import_failed']} failed, "
      f"{r['import_batches_failed']} batches failed, {r['duration_s']:.1f} s")
PY
  # Kratos writes each batch in one transaction before it answers, so the
  # users are usable at once; the admin API finding the last one checks it.
  local last
  last=$(printf 'bulk%08d@%s' "$((to - 1))" "$ORY_HOST")
  until [ "$(curl -fsS --max-time 10 --cacert "$BUNDLE/ca.crt" --resolve "$ORY_HOST:4434:${SERVER_IP:-127.0.0.1}" \
    "https://$ORY_HOST:4434/admin/identities?credentials_identifier=$last" | python3 -I -c 'import json,sys; print(len(json.load(sys.stdin)))')" = 1 ]; do
    sleep 1
  done
  log "Kratos lists the last seeded user after $(($(date +%s) - start)) s"
}

# The parameters of the stored password hashes, counted by PHC prefix (the
# part before the salt). No hash is printed.
cmd_hashes() {
  sql "SELECT substring(config->>'hashed_password' FROM '^[\$][^\$]+[\$][^\$]+[\$][^\$]+'), count(*)
         FROM identity_credentials c JOIN identity_credential_types t ON t.id = c.identity_credential_type_id
        WHERE t.name = 'password' GROUP BY 1"
}

# Messages Kratos has queued for its courier (emails and SMS), by status.
cmd_messages() {
  printf 'courier messages: %s\n' "$(sql 'SELECT count(*) FROM courier_messages')"
}

cmd_restart() {
  compose restart hydra kratos ui
  wait_ready
}

cmd_down() {
  compose down --volumes --remove-orphans
  # The realm went with the database: the next `up` makes it again.
  rm -f "$BUNDLE/realm.done"
}

case ${1:-} in
  bundle) make_bundle ;;
  up) cmd_up ;;
  seed) shift && cmd_seed "$@" ;;
  hashes) cmd_hashes ;;
  messages) cmd_messages ;;
  restart) cmd_restart ;;
  down) cmd_down ;;
  *) sed -n '2,/^set -euo/p' "$0" | sed '$d' >&2 && exit 2 ;;
esac
