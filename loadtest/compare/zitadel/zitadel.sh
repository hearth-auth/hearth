#!/usr/bin/env bash
# Zitadel for the same-hardware comparison (#913): one server with Zitadel and
# its PostgreSQL (compose.yaml), the stress realm (the first instance and
# instance.py), and the seed.
#
# Usage: zitadel.sh <command>
#   up            make the bundle (first time), start PostgreSQL and Zitadel
#                 (init, setup, start), wait until Zitadel is ready, create the
#                 clients and the login users (first time, instance.py)
#   seed <from> <to>
#                 import users without a usable password (instance.py
#                 unusable_hash) bulk<from> .. bulk<to - 1> through
#                 POST /admin/v1/import (k6/prepare.js, PRODUCT=zitadel); prints
#                 the import time (duration_s) from <bundle>/out/seed-<from>-<to>.json,
#                 then waits until Zitadel's user projection has every seeded
#                 user and prints the time until then (the seed time)
#   hashes        print the parameters of the stored password hashes (no hash)
#   restart       restart Zitadel (the data stays)
#   down          remove the containers and the database volume, and with them the
#                 realm (the images and the bundle's passwords stay)
#
# Environment:
#   BUNDLE              the bundle directory (default ../.build/zitadel): CA, TLS
#                       leaf, server.env, generator.env, setup.pat; mode 0700
#   SERVER_IP           the address the generator dials (default 127.0.0.1)
#   ZT_BIND             the address Zitadel listens on (default 127.0.0.1)
#   ZT_PORT             Zitadel's port, inside and outside (default 8443)
#   LOGIN_USERS         users with a password (default 1000, as in #647)
#   IMPORT_BATCH, IMPORT_VUS   seed batch size and concurrency (prepare.js)
#   ZITADEL_MEM_LIMIT   Zitadel's container memory limit (default 2g)
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
compare=$(cd "$here/.." && pwd)
export BUNDLE=${BUNDLE:-$compare/.build/zitadel}
export ZT_HOST=zitadel.stress.test
export ZT_PORT=${ZT_PORT:-8443}
export ZT_ORG=stress
HOST_UID=$(id -u)
HOST_GID=$(id -g)
export HOST_UID HOST_GID
set -a
# shellcheck disable=SC1091
. "$compare/images.env"
set +a

log() { printf 'zitadel: %s\n' "$*" >&2; }
die() {
  log "FAILED: $*"
  exit 2
}
compose() { docker compose -f "$here/compose.yaml" --env-file "$BUNDLE/server.env" "$@"; }
# 24 random letters and digits, plus one of each class that Zitadel's default
# password complexity policy asks for (lower, upper, digit, symbol).
password() { printf '%sa-A1' "$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)"; }
# The masterkey must be exactly 32 characters.
masterkey() { openssl rand -base64 48 | tr -d '/+=' | cut -c1-32; }

make_bundle() {
  [ ! -e "$BUNDLE" ] || return 0
  log "making the bundle in $BUNDLE"
  mkdir -p "$BUNDLE"
  chmod 0700 "$BUNDLE"
  bash "$compare/tls.sh" "$BUNDLE" "$ZT_HOST"
  # Zitadel runs as its image's user and must read the leaf; the bundle
  # directory (0700) keeps other users of this host out.
  chmod 0755 "$BUNDLE/tls"
  chmod 0644 "$BUNDLE/tls/https.key" "$BUNDLE/tls/https.crt"
  local admin_password
  admin_password=$(password)
  (
    umask 077
    # Compose variables (compose.yaml hands each container its own keys).
    {
      printf 'DB_PASSWORD=%s\nDB_ADMIN_PASSWORD=%s\nZITADEL_MASTERKEY=%s\n' \
        "$(password)" "$(password)" "$(masterkey)"
      printf 'ADMIN_EMAIL=admin@%s\nADMIN_PASSWORD=%s\n' "$ZT_HOST" "$admin_password"
    } > "$BUNDLE/server.env"
    # The client ids and secrets are generated by Zitadel; instance.py adds
    # them (STRESS_APP_CLIENT_ID, STRESS_API_*, STRESS_CC_*).
    cat > "$BUNDLE/generator.env" << EOF
PRODUCT=zitadel
STRESS_BASE=https://$ZT_HOST:$ZT_PORT
STRESS_HOST=$ZT_HOST
STRESS_SERVER_IP=${SERVER_IP:-127.0.0.1}
STRESS_REDIRECT_URI=https://app.stress.test/callback
STRESS_LOGIN_USERS=${LOGIN_USERS:-1000}
STRESS_USER_PASSWORD=$(password)
STRESS_ADMIN_EMAIL=admin@$ZT_HOST
STRESS_ADMIN_PASSWORD=$admin_password
STRESS_REALM=$ZT_ORG
EOF
  )
}

ready() {
  curl -fsS -o /dev/null --max-time 4 --cacert "$BUNDLE/ca.crt" \
    --resolve "$ZT_HOST:$ZT_PORT:${SERVER_IP:-127.0.0.1}" "https://$ZT_HOST:$ZT_PORT/debug/ready" 2> /dev/null
}

wait_ready() {
  local i
  for i in $(seq 1 300); do
    if ready; then
      log "Zitadel is ready after ${i} s"
      return 0
    fi
    sleep 1
  done
  compose logs --tail 40 zitadel >&2
  die "Zitadel is not ready after 300 s"
}

cmd_up() {
  make_bundle
  compose up -d
  wait_ready
  # Zitadel's setup writes the PAT world-readable.
  chmod 0600 "$BUNDLE/setup.pat"
  if [ ! -e "$BUNDLE/instance.done" ]; then
    log "creating the clients and the login users"
    python3 -I "$here/instance.py" "$BUNDLE"
    touch "$BUNDLE/instance.done"
  fi
}

# The position of the newest added user, and how far Zitadel's user projection
# (projections.users14 in v4.20.5, the table the user APIs and the login page
# read) has applied the event stream. Only an event type it applies counts: a
# sign-in's password check is a user event that it skips.
sql() { compose exec -T postgres psql -U postgres -d zitadel -At -c "$1"; }
newest_user() {
  sql "SELECT COALESCE(max(position), 0) FROM eventstore.events2 WHERE event_type = 'user.human.added'"
}
projected() {
  sql "SELECT COALESCE(max(position), 0) FROM projections.current_states WHERE projection_name = 'projections.users14'"
}

cmd_seed() {
  local from=${1:?usage: zitadel.sh seed <from> <to>} to=${2:?usage: zitadel.sh seed <from> <to>}
  local out=seed-$from-$to.json start target
  log "seeding users $from .. $((to - 1))"
  start=$(date +%s)
  bash "$compare/k6.sh" "$BUNDLE" prepare.js IMPORT_FROM="$from" IMPORT_TO="$to" \
    IMPORT_BATCH="${IMPORT_BATCH:-1000}" IMPORT_VUS="${IMPORT_VUS:-4}" PREPARE_OUT="/out/$out" > /dev/null
  python3 -I - "$BUNDLE/out/$out" << 'PY'
import json, sys
r = json.load(open(sys.argv[1]))
print(f"seed: {r['users_imported']} imported, {r['users_import_failed']} failed, "
      f"{r['import_batches_failed']} batches failed, {r['duration_s']:.1f} s")
PY
  # The import answers once the events are stored; the users reach the APIs
  # and the login page only when the projection has applied them. A run
  # started before that would share the server with the catch-up.
  target=$(newest_user)
  until python3 -I -c 'import sys; sys.exit(float(sys.argv[1]) < float(sys.argv[2]))' "$(projected)" "$target"; do
    sleep 5
  done
  log "the user projection has every seeded user after $(($(date +%s) - start)) s"
}

# The parameters of the stored password hashes, counted by PHC prefix (the
# part before the salt), from the events that carry a password hash. No hash
# is printed.
cmd_hashes() {
  compose exec -T postgres psql -U postgres -d zitadel -At << 'SQL'
SELECT substring(payload->>'encodedHash' FROM '^[$][^$]+[$][^$]+[$][^$]+'), count(*)
  FROM eventstore.events2
 WHERE aggregate_type = 'user' AND payload ? 'encodedHash'
 GROUP BY 1;
SQL
}

cmd_restart() {
  compose restart zitadel
  wait_ready
}

cmd_down() {
  compose down --volumes --remove-orphans
  # The realm went with the database: the next `up` makes it again.
  rm -f "$BUNDLE/instance.done" "$BUNDLE/setup.pat"
}

case ${1:-} in
  up) cmd_up ;;
  seed) shift && cmd_seed "$@" ;;
  hashes) cmd_hashes ;;
  restart) cmd_restart ;;
  down) cmd_down ;;
  *) sed -n '2,/^set -euo/p' "$0" | sed '$d' >&2 && exit 2 ;;
esac
