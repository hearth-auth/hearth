#!/usr/bin/env bash
# Generates everything one production-mode Hearth server needs for a live
# stress run: secrets, a CA and an HTTPS leaf, the environment file and
# hearth.yaml.
#
# Nothing here is test-only. The config is a production config: no --dev, no
# dev-endpoints, fsync on, TLS on. The only departures from the defaults are
# the limits that one load generator on one IP address would otherwise hit;
# each is listed in the README and in the run report.
#
# Usage: gen-config.sh <out-dir> <server-ip> [login-users]
#   out-dir      must not exist; it receives the bundle (mode 0700)
#   server-ip    the address the generator dials; it goes into the cert SAN
#   login-users  users with a password, declared as seed_users (default 1000)
#
# Layout of <out-dir>:
#   ca.crt ca.key           the run's CA (the generator trusts ca.crt)
#   server/                 copied to /opt/hearth on the server
#     hearth.yaml
#     hearth.env            HEARTH_MASTER_KEY, HEARTH_KEK, the seed passwords
#     tls/https.crt tls/https.key
#   generator.env           what the k6 scripts need (base URL, passwords)
set -euo pipefail

out=${1:?usage: gen-config.sh <out-dir> <server-ip> [login-users]}
server_ip=${2:?usage: gen-config.sh <out-dir> <server-ip> [login-users]}
login_users=${3:-1000}

host=hearth.stress.test
port=8443
realm=stress
redirect_uri=https://app.stress.test/callback

if [ -e "$out" ]; then
  echo "gen-config: $out exists; refusing to overwrite a bundle" >&2
  exit 2
fi
if ! [[ $login_users =~ ^[0-9]+$ ]] || [ "$login_users" -lt 1 ]; then
  echo "gen-config: login-users must be a positive integer" >&2
  exit 2
fi

umask 077
mkdir -p "$out/server/tls"

hex32() { openssl rand -hex 32; }
password() { openssl rand -base64 24 | tr -d '/+=' | cut -c1-24; }

master_key=$(hex32)
kek=$(hex32)
user_password=$(password)
admin_password=$(password)
api_secret=$(password)
metrics_token=$(password)

# CA and HTTPS leaf. rustls checks the SAN, never the CN.
openssl req -x509 -new -nodes -newkey ec -pkeyopt ec_paramgen_curve:P-256 \
  -days 7 -subj "/CN=hearth-stress-ca" \
  -keyout "$out/ca.key" -out "$out/ca.crt" 2> /dev/null
openssl req -new -nodes -newkey ec -pkeyopt ec_paramgen_curve:P-256 \
  -subj "/CN=$host" \
  -keyout "$out/server/tls/https.key" -out "$out/server/tls/https.csr" 2> /dev/null
openssl x509 -req -days 7 -CA "$out/ca.crt" -CAkey "$out/ca.key" -CAcreateserial \
  -extfile <(printf 'subjectAltName=DNS:%s,IP:%s,IP:127.0.0.1\nextendedKeyUsage=serverAuth\n' \
    "$host" "$server_ip") \
  -in "$out/server/tls/https.csr" -out "$out/server/tls/https.crt" 2> /dev/null
rm -f "$out/server/tls/https.csr" "$out/ca.srl"

cat > "$out/server/hearth.env" << EOF
HEARTH_MASTER_KEY=$master_key
HEARTH_KEK=$kek
STRESS_USER_PASSWORD=$user_password
STRESS_ADMIN_PASSWORD=$admin_password
STRESS_API_SECRET=$api_secret
STRESS_METRICS_TOKEN=$metrics_token
EOF

{
  cat << EOF
# Live stress run: one production-mode node. Generated by gen-config.sh.
oidc:
  issuer: "https://$host:$port"
server:
  bind_address: "0.0.0.0"
  port: $port
  tls_cert_path: "/opt/hearth/tls/https.crt"
  tls_key_path: "/opt/hearth/tls/https.key"
security:
  # The generator dials the server by name (hearth.stress.test) and the
  # sampler on the server dials 127.0.0.1.
  allowed_hosts: ["$host", "127.0.0.1"]
  # Every request comes from one generator, one IP address and one realm
  # admin. The defaults (200 token-endpoint requests a minute per client,
  # 100 admin requests a minute, 100 requests a second per IP, 1000 per
  # realm) would measure the limiters instead of the server. The limiters
  # stay on; these values just do not bind.
  rate_limiting:
    token_per_minute: 100000000
    admin_per_minute: 100000000
  request_shaper:
    ip_rps: 1000000
    realm_rps: 1000000
operational:
  # One generator holds one connection per k6 VU (up to several thousand).
  max_connections: 20000
  max_connections_per_ip: 20000
token:
  # Ramps run longer than the 15-minute default; 1 hour is the maximum
  # Hearth accepts (HEA-SEC-27), so every ramp ends within the hour. The
  # lifetime changes no per-request cost.
  access_token_ttl: "1h"
storage:
  data_dir: "/var/lib/hearth/data"
email:
  transport: log
  allow_log_transport_in_production: true
metrics:
  enabled: true
  bearer_token: "\${STRESS_METRICS_TOKEN}"
realms:
  $realm:
    auth:
      mfa_required: false
    applications:
      # Public client: authorization code + PKCE, then refresh tokens. This is
      # how a browser or mobile app signs users in.
      app:
        name: "Stress app"
        redirect_uris: ["$redirect_uri"]
        grant_types: [authorization_code, refresh_token]
        require_consent: false
      # Confidential client for token introspection (a resource server).
      # prepare.js regenerates its secret so each request checks a SHA-256
      # digest, not an Argon2id hash: the way an operator runs a busy API.
      api:
        name: "Stress API"
        confidential: true
        client_secret: "\${STRESS_API_SECRET}"
        grant_types: [client_credentials]
    seed_users:
      - email: "admin@$host"
        display_name: "Stress admin"
        password: "\${STRESS_ADMIN_PASSWORD}"
        roles: [realm.admin]
EOF
  for i in $(seq 1 "$login_users"); do
    printf '      - email: "user%06d@%s"\n        display_name: "User %d"\n        password: "${STRESS_USER_PASSWORD}"\n' \
      "$i" "$host" "$i"
  done
} > "$out/server/hearth.yaml"

# Client IDs of YAML-declared applications: UUID v5 of "<realm>/<key>" in
# Hearth's application namespace (src/identity/reconcile.rs, APP_NAMESPACE).
client_id() {
  python3 -c 'import sys, uuid; print(uuid.uuid5(uuid.UUID("8b074e8c-3e6a-5a8e-961d-8f2baae71bf4"), sys.argv[1]))' "$realm/$1"
}

cat > "$out/generator.env" << EOF
STRESS_BASE=https://$host:$port
STRESS_HOST=$host
STRESS_SERVER_IP=$server_ip
STRESS_REALM=$realm
STRESS_REDIRECT_URI=$redirect_uri
STRESS_APP_CLIENT_ID=$(client_id app)
STRESS_API_CLIENT_ID=$(client_id api)
STRESS_LOGIN_USERS=$login_users
STRESS_USER_PASSWORD=$user_password
STRESS_ADMIN_EMAIL=admin@$host
STRESS_ADMIN_PASSWORD=$admin_password
STRESS_API_SECRET=$api_secret
STRESS_METRICS_TOKEN=$metrics_token
EOF

echo "gen-config: bundle written to $out (server ip $server_ip, $login_users login users)" >&2
